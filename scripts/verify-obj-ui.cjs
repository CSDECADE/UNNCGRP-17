const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');
const { tmpdir } = require('node:os');
const testDir = fs.mkdtempSync(path.join(tmpdir(), 'aero-stage2-ui-'));
app.setPath('userData', path.join(testDir, 'profile'));
app.commandLine.appendSwitch('enable-unsafe-swiftshader');
const timeout = setTimeout(() => { console.error('UI test timed out'); app.exit(1); }, 45000);
app.whenReady().then(async () => {
 const win = new BrowserWindow({ show: false, width: 1440, height: 1000, webPreferences: { contextIsolation: true, nodeIntegration: false, backgroundThrottling: false } });
 const errors = [];
 win.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message); });
 const run = code => win.webContents.executeJavaScript(code, true);
 const wait = async code => { for (let i=0;i<200;i++) { if (await run(code)) return; await new Promise(r=>setTimeout(r,50)); } throw new Error('Timed out: '+code); };
 const click = label => run(`(()=>{const e=document.querySelector('[aria-label="${label}"]'); e.dispatchEvent(new PointerEvent('pointerdown',{button:0,bubbles:true,pointerType:'mouse'})); e.dispatchEvent(new PointerEvent('pointerup',{button:0,bubbles:true,pointerType:'mouse'})); e.click();})()`);
 const key = (key, ctrl=false) => run(`document.body.dispatchEvent(new KeyboardEvent('keydown',{key:${JSON.stringify(key)},code:${JSON.stringify(key===' '?'Space':key)},ctrlKey:${ctrl},bubbles:true}))`);
 const upload = (selector, text, name) => run(`(()=>{const input=document.querySelector(${JSON.stringify(selector)}); const data=new DataTransfer();data.items.add(new File([${JSON.stringify(text)}],${JSON.stringify(name)},{type:'text/plain'})); input.files=data.files;input.dispatchEvent(new Event('change',{bubbles:true}));})()`);
 const stored = () => run("JSON.parse(localStorage.getItem('p15.project.v1'))");
 try {
  await win.loadURL(process.argv[2] || 'http://127.0.0.1:5176/');
  await wait("!!document.querySelector('canvas') && !!document.querySelector('[aria-label=\"添加模型\"]')");
  await wait("!!localStorage.getItem('p15.project.v1')");
  const before=await stored();
  await click('添加模型');
  await wait("[...document.querySelectorAll('[role=menuitem]')].some(x=>x.textContent.includes('导入 OBJ'))");
  await key('Escape');
  const obj='v 40 0 20\nv 60 0 20\nv 60 18 20\nv 40 18 20\no Wall\nf 1 2 3 4\no Side\nv 40 0 8\nv 40 18 8\nf 1 4 6 5\n';
  await upload('input[accept=".obj"]',obj,'ui-building.obj');
  await wait("!!document.querySelector('[aria-label=\"选择 ui-building.obj\"]')");
  await wait("JSON.parse(localStorage.getItem('p15.project.v1')).version===2");
  const imported=await stored();
  assert.equal(imported.models.length,before.models.length+1);
  assert.deepEqual(imported.drones,before.drones); assert.deepEqual(imported.viewpoints,before.viewpoints);
  assert.equal(imported.objResources[0].meshes.length,2);
  assert.equal(await run("document.querySelector('[aria-label=\"选择 ui-building.obj\"]').getAttribute('aria-pressed')"),'true');
  await run("document.activeElement?.blur()");
  await key('z',true); await wait("!document.querySelector('[aria-label=\"选择 ui-building.obj\"]')");
  await run("document.body.dispatchEvent(new KeyboardEvent('keydown',{key:'z',ctrlKey:true,shiftKey:true,bubbles:true}))");
  await wait("!!document.querySelector('[aria-label=\"选择 ui-building.obj\"]')");
  await click('选择 ui-building.obj');
  await click('隐藏 ui-building.obj'); await wait("!!document.querySelector('[aria-label=\"显示 ui-building.obj\"]')");
  await click('显示 ui-building.obj'); await click('锁定 ui-building.obj');
  await key('Delete'); assert.equal(await run("!!document.querySelector('[aria-label=\"选择 ui-building.obj\"]')"),true);
  await click('解锁 ui-building.obj');
  // Verify scene picking through Electron's actual mouse event path at canvas centre.
  await run("document.activeElement?.blur()");
  const rect=await run("(()=>{const r=document.querySelector('canvas').getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()");
  await run("document.querySelector('[aria-label=\"选择 教学楼 A\"]').click()");
  win.webContents.sendInputEvent({type:'mouseDown',button:'left',x:Math.round(rect.x),y:Math.round(rect.y),clickCount:1});
  win.webContents.sendInputEvent({type:'mouseUp',button:'left',x:Math.round(rect.x),y:Math.round(rect.y),clickCount:1});
  await new Promise(r=>setTimeout(r,200));
  const scenePicked=await run("document.querySelector('[aria-label=\"选择 ui-building.obj\"]').getAttribute('aria-pressed')==='true'");
  assert.equal(scenePicked,true,'Native canvas mouse picking should select the imported OBJ');
  await click('选择 ui-building.obj'); await key('f');
  await new Promise(r=>setTimeout(r,250));
  fs.writeFileSync(path.join(testDir,'imported.png'),(await win.webContents.capturePage()).toPNG());
  const downloaded=new Promise((resolve,reject)=>win.webContents.session.once('will-download',(_e,item)=>{
   item.setSavePath(path.join(testDir,'snapshot.json'));item.once('done',(_event,state)=>state==='completed'?resolve():reject(new Error(state)));
  }));
  await run("document.querySelector('.right-topline .primary-button').click()");
  await downloaded;
  const snapshot=fs.readFileSync(path.join(testDir,'snapshot.json'),'utf8');
  assert.equal(JSON.parse(snapshot).objResources[0].meshes.length,2);
  await run("document.activeElement?.blur()"); await click('选择 ui-building.obj'); await key('Delete');
  await wait("!document.querySelector('[aria-label=\"选择 ui-building.obj\"]')");
  await key('z',true); await wait("!!document.querySelector('[aria-label=\"选择 ui-building.obj\"]')");
  await run("document.body.dispatchEvent(new KeyboardEvent('keydown',{key:'z',ctrlKey:true,shiftKey:true,bubbles:true}))");
  await wait("!document.querySelector('[aria-label=\"选择 ui-building.obj\"]')");
  await click('项目菜单');
  await run("[...document.querySelectorAll('[role=menuitem]')].find(x=>x.textContent.includes('打开项目')).click()");
  await upload('input[accept=".json,.p15"]',snapshot,'snapshot.json');
  await wait("!!document.querySelector('[aria-label=\"选择 ui-building.obj\"]')");
  await wait("JSON.parse(localStorage.getItem('p15.project.v1')).models.some(m=>m.kind==='obj')");
  await new Promise(resolve=>{win.webContents.once('did-finish-load',resolve);win.reload();}); await wait("!!document.querySelector('[aria-label=\"选择 ui-building.obj\"]')");
  const restored=await stored(); assert.deepEqual(restored.objResources,JSON.parse(snapshot).objResources);
  await upload('input[accept=".obj"]', 'v 0 0 0\nmtllib bad.mtl', 'bad.obj');
  await wait("document.body.textContent.includes('OBJ 导入失败')");
  assert.equal((await stored()).models.filter(m=>m.kind==='obj').length,1);
  await click('预演方案'); await click('播放航线');
  await wait("document.querySelector('[aria-label=\"暂停航线\"]')!==null");
  await click('暂停航线'); await click('退出预演');
  await click('多机路径分析');
  await wait("!!document.querySelector('.route-analysis table')");
  assert.equal(await run("document.querySelectorAll('.route-analysis table:first-of-type tbody tr').length > 0"),true);
  await click('关闭弹窗');
  await run("window.__originalSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(){throw new DOMException('quota','QuotaExceededError')};void 0");
  await upload('input[accept=".obj"]',obj,'quota-building.obj');
  await wait("!!document.querySelector('[aria-label=\"选择 quota-building.obj\"]')");
  await wait("document.querySelector('.persistent-notice')?.textContent.includes('本机暂存失败')");
  const quotaDownload=new Promise((resolve,reject)=>win.webContents.session.once('will-download',(_e,item)=>{
   item.setSavePath(path.join(testDir,'quota-snapshot.json'));item.once('done',(_event,state)=>state==='completed'?resolve():reject(new Error(state)));
  }));
  await run("document.querySelector('.right-topline .primary-button').click()");
  await quotaDownload;
  const quotaSnapshot=JSON.parse(fs.readFileSync(path.join(testDir,'quota-snapshot.json'),'utf8'));
  assert.equal(quotaSnapshot.models.filter(m=>m.kind==='obj').length,2);
  assert.equal(quotaSnapshot.objResources.length,2);
  await run("Storage.prototype.setItem=window.__originalSetItem;delete window.__originalSetItem");
  assert.equal(errors.length,0,JSON.stringify(errors));
  console.log(JSON.stringify({passed:true,scenePicked,screenshot:path.join(testDir,'imported.png'),snapshot:path.join(testDir,'snapshot.json'),checks:['import-menu','file-input','multi-mesh','selection','visibility','lock-delete','focus','save-download','undo-import','undo-redo','restore-file','reload-autosave','invalid-input','playback','analysis','quota-failure-save-fallback','no-console-errors']}));
  clearTimeout(timeout);app.exit(0);
 } catch(error) { console.error(error); console.error('rendererErrors',errors); clearTimeout(timeout);app.exit(1); }
});
