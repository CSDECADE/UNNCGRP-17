const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

// Reuse the 3A native pointer/text harness rather than creating another UI driver.
module.exports = async function verifyBuiltins({win,run,wait,click,key,snapshot,delay,input,
 dragStart,dragMove,release,setupRoot,control,before,testDir}) {
 const near=(a,b,eps=1e-4)=>a.forEach((n,i)=>assert.ok(Math.abs(n-b[i])<eps,`${a} != ${b}`));
 const selected=id=>snapshot().then(p=>p.models.find(m=>m.id===id));
 const checks=[];
 const renderedSize=id=>run(`(async()=>{const {Box3,Vector3}=await import('/node_modules/.vite/deps/three.js');
  const root=window.__root.getState(),model=root.scene.getObjectByName('model-${id}');root.scene.updateMatrixWorld(true);
  const box=new Box3();model.traverse(o=>{if(!o.isMesh||o.material?.opacity===0)return;
   for(let p=o;p&&p!==model;p=p.parent)if(p.userData.editorOverlay)return;
   o.geometry.computeBoundingBox();box.union(o.geometry.boundingBox.clone().applyMatrix4(o.matrixWorld));});
  return box.getSize(new Vector3()).toArray();})()`);
 for(const kind of ['building','box','cylinder']){
  const original=before.models.find(m=>m.kind===kind);assert.ok(original,kind);
  await click('选择 '+original.name);await key('f');await delay(80);
  await wait("!!document.querySelector('input[aria-label=\"尺寸 X\"]')");
  assert.equal(await run("!!document.querySelector('input[aria-label=\"旋转 X\"]')"),false);
  assert.equal(await run("!!document.querySelector('input[aria-label=\"旋转 Z\"]')"),false);
  await click('移动 M');await wait(`!!(${control}?.object)`);
  const start=await dragStart('X'),end=await dragMove(start);await release(end);
  const translated=await selected(original.id);assert.ok(Math.abs(translated.position[0]-original.position[0])>.01);
  near([Number(await run("document.querySelector('input[aria-label=\"位置 X\"]').value"))],[translated.position[0]]);
  await run('document.activeElement?.blur()');await key('z',true);await delay(550);near((await selected(original.id)).position,original.position);
  await key('z',true,true);await delay(550);near((await selected(original.id)).position,translated.position);
  const cancelledStart=await dragStart('Y'),cancelledEnd=await dragMove(cancelledStart);
  await key('Escape');await release(cancelledEnd);near((await selected(original.id)).position,translated.position);
  await key('z',true);await delay(550);near((await selected(original.id)).position,original.position);
  await key('z',true,true);await delay(550);near((await selected(original.id)).position,translated.position);
  await click('旋转 R');await wait(`!!(${control}?.object)`);
  const enabledAxes=await run(`(()=>{const c=${control};return [c.showX,c.showY,c.showZ,c.showE,c.showXYZE]})()`);
  assert.deepEqual(enabledAxes,[false,true,false,false,false]);
  const rotateStart=await dragStart('Y'),rotateEnd=await dragMove(rotateStart,true);await release(rotateEnd);
  assert.ok(Math.abs((await selected(original.id)).rotation-translated.rotation)>.1);
  await input('旋转 Y',0);
  const dimensionsBefore=await renderedSize(original.id);
  const sizeBefore=(await selected(original.id)).size;
  const numericSize=[sizeBefore[0]*1.25,sizeBefore[1]*.75,sizeBefore[2]*1.5];
  await input('尺寸 X',numericSize[0]);await input('尺寸 Y',numericSize[1]);await input('尺寸 Z',numericSize[2]);
  near((await selected(original.id)).size,numericSize);
  near((await selected(original.id)).position,translated.position);
  const dimensionsAfter=await renderedSize(original.id);
  near(dimensionsAfter.map((n,i)=>n/dimensionsBefore[i]),numericSize.map((n,i)=>n/sizeBefore[i]),1e-4);
  near(await run(`window.__root.getState().scene.getObjectByName('model-${original.id}').scale.toArray()`),[1,1,1]);
  await input('旋转 Y',125.5);assert.ok(Math.abs((await selected(original.id)).rotation-125.5)<1e-8);
  await click('缩放 K');await wait(`!!(${control}?.object)`);
  const scaleStart=await dragStart('X'),scaleEnd=await dragMove(scaleStart);await release(scaleEnd);
  const resized=await selected(original.id);assert.ok(Math.abs(resized.size[0]-numericSize[0])>.01);
  near(resized.size.slice(1),numericSize.slice(1));near(resized.position,translated.position);
  const uniformStart=await dragStart('XYZ'),uniformEnd=await dragMove(uniformStart);await release(uniformEnd);
  const uniform=await selected(original.id),ratios=uniform.size.map((n,i)=>n/resized.size[i]);
  near(ratios,[ratios[0],ratios[0],ratios[0]]);assert.ok(Math.abs(ratios[0]-1)>.01);
  near(uniform.position,translated.position);
  assert.equal(Object.hasOwn(uniform,'scale'),false);assert.equal(Object.hasOwn(uniform,'rotationXYZ'),false);
  await click('锁定 '+original.name);await wait(`!(${control})`);
  assert.equal(await run("document.querySelector('input[aria-label=\"尺寸 X\"]').disabled"),true);
  await click('解锁 '+original.name);await wait(`!!(${control}?.object)`);
  await click('隐藏 '+original.name);await wait(`!(${control})`);await click('显示 '+original.name);await wait(`!!(${control}?.object)`);
  checks.push(`${kind}: native move/yaw/dimensions, numeric-render sync, cancel/history, visibility/lock`);
 }
 await click('预演方案');await wait(`!(${control})`);
 assert.equal(await run("document.querySelector('input[aria-label=\"位置 X\"]').disabled"),true);
 await click('播放航线');await wait("!!document.querySelector('[aria-label=\"暂停航线\"]')");await delay(250);
 await click('暂停航线');await click('退出预演');await click('缩放 K');await wait(`!!(${control}?.object)`);
 await click('多机路径分析');await wait("!!document.querySelector('.route-analysis table')");
 const plan=JSON.stringify({version:1,viewpoints:before.viewpoints});
 await run(`(()=>{const i=document.querySelector('.route-analysis input[type=file]'),d=new DataTransfer();d.items.add(new File([${JSON.stringify(plan)}],'candidate.json'));i.files=d.files;i.dispatchEvent(new Event('change',{bubbles:true}));})()`);
 await wait("!!document.querySelector('.candidate-banner')");await click('关闭弹窗');
 assert.equal(await run(`!!(${control})`),false);
 assert.equal(await run("document.querySelector('input[aria-label=\"尺寸 X\"]').disabled"),true);
 await run("[...document.querySelectorAll('.candidate-banner button')].find(e=>e.textContent.includes('取消')).click()");
 await click('选择 '+before.models.find(m=>m.kind==='building').name);await key('f');await click('移动 M');await wait(`!!(${control}?.object)`);
 await delay(550);
 const final=await snapshot();assert.equal(final.version,1);assert.deepEqual(final.drones,before.drones);assert.deepEqual(final.viewpoints,before.viewpoints);
 fs.writeFileSync(path.join(testDir,'builtins.png'),(await win.webContents.capturePage()).toPNG());
 const saved=new Promise((resolve,reject)=>win.webContents.session.once('will-download',(_e,item)=>{item.setSavePath(path.join(testDir,'builtins.json'));item.once('done',(_e,state)=>state==='completed'?resolve():reject(new Error(state)));}));
 await run("document.querySelector('.right-topline .primary-button').click()");await saved;
 assert.deepEqual(JSON.parse(fs.readFileSync(path.join(testDir,'builtins.json'),'utf8')),final);
 await new Promise(resolve=>{win.webContents.once('did-finish-load',resolve);win.reload();});
 await wait("!!document.querySelector('canvas')");await setupRoot();
 await wait(`!!window.__root.getState().scene.getObjectByName('model-${before.models[0].id}')`);
 assert.deepEqual((await snapshot()).models,final.models);
 for(const m of final.models){await click('选择 '+m.name);await wait("!!document.querySelector('input[aria-label=\"尺寸 Y\"]')");
  near([Number(await run("document.querySelector('input[aria-label=\"尺寸 Y\"]').value"))],[m.size[1]]);}
 await click('选择 '+before.drones[0].name);
 assert.equal(await run("!!document.querySelector('.model-transform-inspector')"),false);
 await click('移动 M');assert.equal(await run(`!!(${control})`),false);
 checks.push('version-1 save/reload, preview/candidate restrictions, UAV playback/analysis regression, no UAV editing');
 return checks;
};
